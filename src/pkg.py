def package_names(config: dict[str, Any]) -> list[str]:
    """Return package names as a normalized list."""

    names = config.get("name")

    if isinstance(names, str):
        return [names]

    if isinstance(names, list) and all(
        isinstance(name, str) and name for name in names
    ):
        return names

    raise RuntimeError(
        "'name' must be a string or a non-empty list of strings"
    )


def install_apt(
    config: dict[str, Any],
) -> None:
    """Install one or more Debian packages using apt."""

    names = package_names(config)

    run([
        "sudo",
        "apt-get",
        "install",
        "-y",
        *names,
    ])


def install_pacman(
    config: dict[str, Any],
) -> None:
    """Install one or more Arch packages using pacman."""

    names = package_names(config)

    run([
        "sudo",
        "pacman",
        "-S",
        "--needed",
        "--noconfirm",
        *names,
    ])


def install_aur(
    config: dict[str, Any],
) -> None:
    """Install one or more AUR packages using yay."""

    names = package_names(config)

    if not command_exists("yay"):
        raise RuntimeError(
            "AUR provider requires 'yay', "
            "but yay is not installed"
        )

    run([
        "yay",
        "-S",
        "--needed",
        "--noconfirm",
        *names,
    ])


def install_github_appimage(
    package_name: str,
    command: str,
    config: dict[str, Any],
    arch: str,
) -> None:
    """
    Install a GitHub AppImage.

    Layout:

        ~/.local/opt/<package>/<version>/<binary>

        ~/.local/opt/<package>/current
            -> <version>

        ~/.local/bin/<command>
            -> ~/.local/opt/<package>/current/<binary>
    """

    repo = config["repo"]
    assets = config["assets"]

    if arch not in assets:
        raise RuntimeError(
            f"{package_name}: no GitHub asset "
            f"configured for architecture {arch!r}"
        )

    asset_config = assets[arch]

    asset_pattern = asset_config["name"]
    binary_name = asset_config.get(
        "binary",
        command,
    )

    # ------------------------------------------------------------------
    # Query GitHub
    # ------------------------------------------------------------------

    pkg_print(
        f"Checking GitHub release: {repo}",
        color=Colors.YELLOW,
    )

    release = github_latest_release(repo)

    tag = release.get("tag_name")

    if not tag:
        raise RuntimeError(
            f"{package_name}: GitHub release has no tag_name"
        )

    asset = github_find_asset(
        release,
        asset_pattern,
    )

    asset_name = asset["name"]
    download_url = asset["browser_download_url"]

    pkg_print(
        f"{package_name}: "
        f"latest release = {tag}, "
        f"asset = {asset_name}",
        color=Colors.YELLOW,
    )

    # ------------------------------------------------------------------
    # Paths
    # ------------------------------------------------------------------

    package_root = LOCAL_OPT / package_name
    version_root = package_root / tag

    current_link = package_root / "current"

    executable = version_root / binary_name
    command_link = LOCAL_BIN / command

    LOCAL_BIN.mkdir(
        parents=True,
        exist_ok=True,
    )

    package_root.mkdir(
        parents=True,
        exist_ok=True,
    )

    # ------------------------------------------------------------------
    # Download
    # ------------------------------------------------------------------

    if not executable.exists():
        version_root.mkdir(
            parents=True,
            exist_ok=True,
        )

        download_path = version_root / asset_name

        if not download_path.exists():
            download_file(
                download_url,
                download_path,
            )

        # The AppImage itself is the executable.
        #
        # We rename it to the logical command name so:
        #
        #   ~/.local/opt/neovim/v0.12.5/nvim
        #
        # is used instead of:
        #
        #   ~/.local/opt/neovim/v0.12.5/nvim-linux-arm64.appimage
        if download_path != executable:
            download_path.rename(executable)

        # Ensure executable permission is present.
        executable.chmod(
            executable.stat().st_mode | 0o111
        )

        pkg_print(
            f"Installed {package_name} {tag}",
            color=Colors.GREEN,
            bold=True,
        )

    else:
        pkg_print(
            f"{package_name} {tag} is already installed",
            color=Colors.GREEN,
        )

    # ------------------------------------------------------------------
    # Update "current" symlink
    # ------------------------------------------------------------------

    if current_link.exists() or current_link.is_symlink():
        if not current_link.is_symlink():
            raise RuntimeError(
                f"Refusing to replace non-symlink: "
                f"{current_link}"
            )

        current_link.unlink()

    current_link.symlink_to(tag)

    # ------------------------------------------------------------------
    # Update ~/.local/bin/<command>
    # ------------------------------------------------------------------

    if command_link.exists() or command_link.is_symlink():
        if not command_link.is_symlink():
            raise RuntimeError(
                f"Refusing to replace non-symlink: "
                f"{command_link}"
            )

        command_link.unlink()

    command_link.symlink_to(
        current_link / binary_name
    )

    pkg_print(
        f"Linked {command_link} -> "
        f"{command_link.resolve()}",
        color=Colors.GREEN,
    )


