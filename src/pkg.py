def install_package(
    package_name: str,
    package: dict[str, Any],
    distro: str,
) -> None:
    """Install one logical package."""

    config = package.get(distro)

    if config is None:
        raise RuntimeError(
            f"{package_name}: "
            f"no configuration for distro {distro!r}"
        )

    provider = config.get("provider")

    if not provider:
        raise RuntimeError(
            f"{package_name}: provider is missing "
            f"for distro {distro!r}"
        )

    pkg_print()
    pkg_print(
        f"==> {package_name} "
        f"[{distro}/{provider}]",
        color=Colors.MAGENTA,
        bold=True,
    )

    if provider == "apt":
        install_apt(config)

    elif provider == "pacman":
        install_pacman(config)

    elif provider == "aur":
        install_aur(config)

    elif provider == "github":
        github_type = config.get("type")

        if github_type == "appimage":
            install_github_appimage(
                package_name=package_name,
                command=package["command"],
                config=config,
                arch=detect_arch(),
            )

        else:
            raise RuntimeError(
                f"{package_name}: "
                f"unsupported GitHub type "
                f"{github_type!r}"
            )

    else:
        raise RuntimeError(
            f"{package_name}: "
            f"unknown provider {provider!r}"
        )


# ---------------------------------------------------------------------------
# Check
# ---------------------------------------------------------------------------

def check_packages(
    packages: dict[str, Any],
    distro: str,
) -> bool:
    """
    Check package installation state and available versions.

    Returns True if every configured package is installed. Version lookup
    failures do not by themselves make the check fail.
    """

    success = True

    pkg_print()
    pkg_print(
        f"{'Package':<20} {'Installed':<24} {'Available':<24} Status",
        color=Colors.BOLD,
    )
    pkg_print(
        f"{'-' * 20} {'-' * 24} {'-' * 24} {'-' * 12}",
        color=Colors.DIM,
    )

    for name, package in packages.items():
        command = package.get("command")
        config = package.get(distro, {})
        provider = config.get("provider")

        # A command-based package (e.g. a GitHub AppImage) is checked via
        # its executable. OS package groups are checked package-by-package.
        if command:
            if not command_exists(command):
                pkg_print(
                    f"{name:<20} {'not installed':<24} {'-':<24} "
                    f"{'[MISSING]'}",
                    color=Colors.RED,
                )
                success = False
                continue

            installed_version = None
            available_version = None

            try:
                if provider == "github" and config.get("type") == "appimage":
                    installed_version = github_installed_version(name)
                    available_version = github_release_version(
                        config["repo"]
                    )
                elif provider == "apt":
                    names = package_names(config)
                    if len(names) == 1:
                        installed_version, available_version = check_apt_package(
                            names[0]
                        )
                elif provider in {"pacman", "aur"}:
                    names = package_names(config)
                    if len(names) == 1:
                        installed_version, available_version = check_pacman_package(
                            names[0]
                        )

                if installed_version is None:
                    installed_version = command_version(command)

            except Exception as exc:
                pkg_print(
                    f"{name}: version check failed: {exc}",
                    color=Colors.YELLOW,
                )

            installed_display = installed_version or "unknown"
            available_display = available_version or "unknown"

            if (
                installed_version
                and available_version
                and versions_differ(installed_version, available_version)
            ):
                status = "[UPDATE]"
                color = Colors.YELLOW
            else:
                status = "[ OK ]"
                color = Colors.GREEN

            pkg_print(
                f"{name:<20} {installed_display:<24} "
                f"{available_display:<24} {status}",
                color=color,
            )
            continue

        # Grouped OS packages have no single command. Check each package.
        try:
            names = package_names(config)
        except Exception as exc:
            pkg_print(
                f"{name}: package check failed: {exc}",
                color=Colors.RED,
            )
            success = False
            continue

        for package_name in names:
            installed_version = None
            available_version = None

            try:
                if provider == "apt":
                    installed_version, available_version = check_apt_package(
                        package_name
                    )
                elif provider in {"pacman", "aur"}:
                    installed_version, available_version = check_pacman_package(
                        package_name
                    )
                else:
                    raise RuntimeError(
                        f"unsupported provider {provider!r}"
                    )
            except Exception as exc:
                pkg_print(
                    f"{name}/{package_name}: version check failed: {exc}",
                    color=Colors.YELLOW,
                )

            if installed_version is None:
                pkg_print(
                    f"{name}/{package_name:<15} "
                    f"{'not installed':<24} {'-':<24} [MISSING]",
                    color=Colors.RED,
                )
                success = False
                continue

            installed_display = installed_version
            available_display = available_version or "unknown"

            if (
                available_version
                and versions_differ(installed_version, available_version)
            ):
                status = "[UPDATE]"
                color = Colors.YELLOW
            else:
                status = "[ OK ]"
                color = Colors.GREEN

            pkg_print(
                f"{name}/{package_name:<15} "
                f"{installed_display:<24} "
                f"{available_display:<24} {status}",
                color=color,
            )

    pkg_print()
    return success


