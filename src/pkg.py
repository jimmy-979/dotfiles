def github_latest_release(repo: str) -> dict[str, Any]:
    """
    Fetch the latest GitHub release for a repository.

    Example:
        neovim/neovim
    """

    url = (
        f"https://api.github.com/repos/"
        f"{repo}/releases/latest"
    )

    request = urllib.request.Request(
        url,
        headers={
            "Accept": "application/vnd.github+json",
            "User-Agent": "dotfiles-pkg",
        },
    )

    try:
        with urllib.request.urlopen(request) as response:
            data = response.read()

    except Exception as exc:
        raise RuntimeError(
            f"Failed to query GitHub release for {repo}: {exc}"
        ) from exc

    try:
        return json.loads(data)
    except json.JSONDecodeError as exc:
        raise RuntimeError(
            f"Invalid JSON returned by GitHub for {repo}"
        ) from exc


def github_find_asset(
    release: dict[str, Any],
    pattern: str,
) -> dict[str, Any]:
    """
    Find a release asset matching a shell-style glob.

    Example:

        nvim-linux-*.appimage
    """

    assets = release.get("assets", [])

    for asset in assets:
        name = asset.get("name")

        if name and fnmatch.fnmatch(name, pattern):
            return asset

    raise RuntimeError(
        f"No GitHub release asset matching {pattern!r} "
        f"was found"
    )


def download_file(
    url: str,
    destination: Path,
) -> None:
    """Download a URL to a local file."""

    destination.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    pkg_print(
        f"Downloading {url}",
        color=Colors.YELLOW,
    )

    request = urllib.request.Request(
        url,
        headers={
            "User-Agent": "dotfiles-pkg",
        },
    )

    try:
        with urllib.request.urlopen(request) as response:
            with destination.open("wb") as f:
                shutil.copyfileobj(response, f)

    except Exception as exc:
        if destination.exists():
            destination.unlink()

        raise RuntimeError(
            f"Failed to download {url}: {exc}"
        ) from exc


