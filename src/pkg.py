def run(
    cmd: list[str],
    *,
    check: bool = True,
) -> subprocess.CompletedProcess[str]:
    """
    Run a Linux command.

    The command itself is printed by pkg in blue, while the command's
    stdout/stderr remain untouched so apt/pacman/yay retain their own
    normal terminal output.
    """

    pkg_print(
        f"$ {' '.join(cmd)}",
        color=Colors.BLUE,
        bold=True,
    )

    return subprocess.run(
        cmd,
        check=check,
        text=True,
    )


def command_exists(command: str) -> bool:
    """Return True if command is available in PATH."""

    return shutil.which(command) is not None


def command_version(command: str) -> str | None:
    """Try to obtain a command's version string."""

    for args in (["--version"], ["-version"], ["version"]):
        try:
            result = subprocess.run(
                [command, *args],
                capture_output=True,
                text=True,
                check=False,
            )
        except OSError:
            continue

        output = (result.stdout or result.stderr).strip()
        if output:
            return output.splitlines()[0].strip()

    return None


def github_release_version(repo: str) -> str:
    """Return the latest GitHub release tag for a repository."""

    release = github_latest_release(repo)
    tag = release.get("tag_name")

    if not tag:
        raise RuntimeError(
            f"{repo}: GitHub release has no tag_name"
        )

    return str(tag)


def github_installed_version(package_name: str) -> str | None:
    """Return the installed version for a GitHub AppImage package."""

    package_root = LOCAL_OPT / package_name
    current_link = package_root / "current"

    if not current_link.is_symlink():
        return None

    try:
        return current_link.resolve().name
    except OSError:
        return None


def normalize_version(version: str) -> tuple:
    """
    Convert a version-like string into comparable components.

    This intentionally keeps comparison simple and works for common tags
    such as v0.12.5, 0.12.5, and release-0.12.5.
    """

    value = version.strip()

    # Remove a common leading 'v'.
    value = re.sub(r"^[vV]", "", value)

    parts = re.findall(r"\\d+|[A-Za-z]+", value)

    normalized = []
    for part in parts:
        if part.isdigit():
            normalized.append((0, int(part)))
        else:
            normalized.append((1, part.lower()))

    return tuple(normalized)


def versions_differ(installed: str, latest: str) -> bool:
    """Return True when the installed and latest versions differ."""

    return normalize_version(installed) != normalize_version(latest)


def check_apt_package(name: str) -> tuple[str | None, str | None]:
    """
    Return (installed_version, candidate_version) for an apt package.

    The candidate version is the version apt currently knows about.
    """

    installed = subprocess.run(
        ["dpkg-query", "-W", "-f=${Version}", name],
        capture_output=True,
        text=True,
        check=False,
    )

    if installed.returncode != 0:
        return None, None

    installed_version = installed.stdout.strip() or None

    candidate = subprocess.run(
        ["apt-cache", "policy", name],
        capture_output=True,
        text=True,
        check=False,
    )

    candidate_version = None

    for line in candidate.stdout.splitlines():
        if line.strip().startswith("Candidate:"):
            candidate_version = line.split(":", 1)[1].strip()
            break

    return installed_version, candidate_version


def check_pacman_package(name: str) -> tuple[str | None, str | None]:
    """
    Return (installed_version, repository_version) for a pacman package.
    """

    installed = subprocess.run(
        ["pacman", "-Q", name],
        capture_output=True,
        text=True,
        check=False,
    )

    if installed.returncode != 0:
        return None, None

    fields = installed.stdout.strip().split()
    installed_version = fields[1] if len(fields) >= 2 else None

    candidate = subprocess.run(
        ["pacman", "-Si", name],
        capture_output=True,
        text=True,
        check=False,
    )

    candidate_version = None

    for line in candidate.stdout.splitlines():
        if line.strip().startswith("Version"):
            candidate_version = line.split(":", 1)[1].strip()
            break

    return installed_version, candidate_version


def load_manifest() -> dict[str, Any]:
    """Load packages.toml."""

    if not MANIFEST.exists():
        raise RuntimeError(
            f"Package manifest not found: {MANIFEST}"
        )

    with MANIFEST.open("rb") as f:
        return tomllib.load(f)


