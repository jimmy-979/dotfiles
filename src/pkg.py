# ---------------------------------------------------------------------------
# Colors / terminal output
# ---------------------------------------------------------------------------

class Colors:
    RESET = "\033[0m"

    RED = "\033[31m"
    GREEN = "\033[32m"
    YELLOW = "\033[33m"
    BLUE = "\033[34m"
    MAGENTA = "\033[35m"
    CYAN = "\033[36m"

    BOLD = "\033[1m"
    DIM = "\033[2m"

    @classmethod
    def enabled(cls) -> bool:
        """
        Return whether ANSI colors should be used.

        Colors are disabled when:
          - stdout is not a terminal
          - NO_COLOR is set
          - TERM=dumb
        """

        return (
            sys.stdout.isatty()
            and "NO_COLOR" not in os.environ
            and os.environ.get("TERM") != "dumb"
        )

    @classmethod
    def wrap(
        cls,
        text: str,
        color: str,
    ) -> str:
        """Wrap text in an ANSI color when colors are enabled."""

        if not cls.enabled():
            return text

        return f"{color}{text}{cls.RESET}"


def pkg_print(
    message: str = "",
    *,
    color: str = Colors.CYAN,
    bold: bool = False,
) -> None:
    """
    Print output generated by pkg itself.

    All pkg-generated output gets a `pkg:` prefix, making it easy
    to distinguish from output produced by apt/pacman/yay.
    """

    if (not message):
        print()
        return

    text = f"pkg: {message}"

    if bold and Colors.enabled():
        text = f"{Colors.BOLD}{text}{Colors.RESET}"

    if color:
        text = Colors.wrap(text, color)

    print(text)


def pkg_error(message: str) -> None:
    """Print an error generated by pkg."""

    text = f"pkg: error: {message}"

    if Colors.enabled():
        text = Colors.wrap(text, Colors.RED)

    print(text, file=sys.stderr)


