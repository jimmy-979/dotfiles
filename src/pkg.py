def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="pkg",
        description=(
            "Cross-distro package manager "
            "for dotfiles"
        ),
    )

    parser.add_argument(
        "--version",
        action="version",
        version=f"%(prog)s {PKG_VERSION}",
    )

    subparsers = parser.add_subparsers(
        dest="action",
        required=True,
    )

    # ------------------------------------------------------------------
    # install
    # ------------------------------------------------------------------

    install_parser = subparsers.add_parser(
        "install",
        help="Install packages",
    )

    install_parser.add_argument(
        "packages",
        nargs="*",
        help=(
            "Packages to install. "
            "If omitted, install everything."
        ),
    )

    # ------------------------------------------------------------------
    # check
    # ------------------------------------------------------------------

    subparsers.add_parser(
        "check",
        help="Check installed packages",
    )

    return parser


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()

    manifest = load_manifest()
    packages = manifest.get("packages")

    if not isinstance(packages, dict):
        raise RuntimeError(
            "packages.toml does not contain "
            "a [packages.*] section"
        )

    distro = detect_distro()
    arch = detect_arch()

    pkg_print(
        f"Distribution : {distro}",
        color=Colors.CYAN,
    )

    pkg_print(
        f"Architecture : {arch}",
        color=Colors.CYAN,
    )

    # ------------------------------------------------------------------
    # check
    # ------------------------------------------------------------------

    if args.action == "check":
        pkg_print(
            f"pkg version    : {PKG_VERSION}",
            color=Colors.CYAN,
        )
        return 0 if check_packages(packages, distro) else 1

    # ------------------------------------------------------------------
    # install
    # ------------------------------------------------------------------

    if args.action == "install":
        requested = args.packages

        if requested:
            names = requested
        else:
            names = list(packages.keys())

        for name in names:
            if name not in packages:
                raise RuntimeError(
                    f"Unknown package: {name}"
                )

            install_package(
                package_name=name,
                package=packages[name],
                distro=distro,
            )

            configure_package(
                package_name=name,
                package=packages[name],
            )

        pkg_print()
        pkg_print(
            "Installation complete",
            color=Colors.GREEN,
            bold=True,
        )

        return 0

    raise RuntimeError(
        f"Unknown action: {args.action}"
    )


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    try:
        sys.exit(main())

    except KeyboardInterrupt:
        pkg_print(
            "Interrupted",
            color=Colors.YELLOW,
        )
        sys.exit(130)

    except subprocess.CalledProcessError as exc:
        pkg_error(
            f"command failed with exit code {exc.returncode}"
        )
        sys.exit(exc.returncode)

    except Exception as exc:
        pkg_error(str(exc))
        sys.exit(1)
